# 6. 잔디의 가격은 1 제곱 미터에 a원일 때  윗변이 b,아래변이 c,
#  높이d인 사다리꼴에 잔디를 심으려면 얼마의 비용이 드는지 
# 구하는 순서도를 작성하시오.

#가격을 입력받아 사다리꼴에 넓이를 곱해주면 된다.
#( 윗변+ 아랫변 )* 높이 / 2
a= int(input("잔디 가격은?"))

b=int(input("윗변>>"))
c=int(input("아랫변>>"))
d=int(input("높이>>"))

total=a*(b+c)*d//2

print("총 잔디 비용은?",a*(b+c)*d//2)
print(f"총 잔디 구매 비용은 {total:,}원 입니다.")

#문자열 앞에 f를 붙이고 따옴표 안에 중괄호 {}를 쓰는 방식을 파이썬에서는
#'f-스트링(f-string)'이라고 부릅니다.중괄호 {}를 사용하는 핵심 이유는
#  문자열 중간에 변수나 계산식을 간편하게 집어넣기 위해서입니다.
# 1. 문자와 변수를 깔끔하게 합쳐줍니다만약 중괄호 {}와 f를 쓰지 않는다면,
#  문자와 변수를 합치기 위해 더하기(+) 기호를 쓰거나 변수를 문자로 바꾸는
#  복잡한 과정을 거쳐야 합니다.
# 기존 방식 (불편함): print("총 잔디 비용은 " + str(total_cost) + "원입니다.")
# f-스트링 방식 (편리함): print(f"총 잔디 비용은 {total_cost}원입니다.")
# 중괄호 안에 변수 이름만 적어주면 파이썬이 알아서 그 자리에 변수의 실제 값을
#  쏙 넣어줍니다.2. 값의 출력 형태(포맷)를 지정할 수 있습니다중괄호 {} 안에서는 
# 변수 이름 뒤에 콜론(:)을 붙여서 "이 값을 어떤 모양으로 보여줄지" 
# 설정할 수 있습니다.작성하셨던 코드의 {total_cost:,}에서 ,(쉼표)가 바로
#  그 역할을 합니다.변수 뒤에 :,를 붙이면 파이썬이 숫자를 인식하고 천 단위마다 
# 자동으로 쉼표를 찍어줍니다. (예: 50000 ➡️ 50,000)


# 사용자로부터 두 수를 입력받습니다. (소수점 입력도 가능하도록 float 사용)
num1 = float(input("첫 번째 수를 입력하세요: "))
num2 = float(input("두 번째 수를 입력하세요: "))

# abs() 함수를 사용하여 두 수의 절대값 차이를 계산합니다.
difference = abs(num1 - num2)

# 앞서 배운 f-스트링을 활용해 결과를 출력합니다. 
# 결과가 정수처럼 딱 떨어지면 보기 좋게 정수형(int)으로 변환하여 보여줍니다.
if difference.is_integer():
    difference = int(difference)

print(f"두 수의 차는 {difference}입니다.")

package com.the.ex;

public class ClassStart10 {

	public static void main(String[] args) {
	//1 , 0, -1   에 대한 음수 양수 풀력 프로그램
		int number=10;
		
		switch(number) {
		case 1: 
			System.out.println("양수");
			break;
		case 0: 
			System.out.println("0");
			break;
		case -1: 
			System.out.println("음수");
			break;	
		default:
			System.out.println("범위에 벗어난 숫자입니다.");
			
		
		}
		
	}

}
